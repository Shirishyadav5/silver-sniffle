package Polymorphism.Methodoverloading;

public class Test1
{
    void m1()
    {
        System.out.println("m1 method");
    }
    public void m2(int a)
    {
        System.out.println(a);
    }
    void m3(int b, int c)
    {
        System.out.println(b+c);
    }
    void m4(int x, int y, int z)
    {
        System.out.println(x+y+z);
    }
}
