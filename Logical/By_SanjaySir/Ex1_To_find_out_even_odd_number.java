public class Ex1_To_find_out_even_odd_number
{
//    To find out given number is even or odd

    static void main(String[] args) {

        int num=6;

        if (num % 2==0)
        {
            System.out.println("Given number is even");
        }
        else
        {
            System.out.println("Given number is odd");
        }
    }
}
